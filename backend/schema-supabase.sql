create extension if not exists pgcrypto;

create table if not exists public.dr1p_cupones (
  codigo text primary key,
  email_hash text,
  premio text not null check (premio in ('10OFF', '15OFF', '20OFF', '5000')),
  usado boolean not null default false,
  fecha timestamptz not null default now(),
  usado_en timestamptz,
  expira_en timestamptz not null default (now() + interval '24 hours')
);

alter table public.dr1p_cupones add column if not exists email_hash text;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'dr1p_cupones' and column_name = 'email'
  ) then
    execute 'update public.dr1p_cupones set email_hash = encode(digest(lower(trim(email)), ''sha256''), ''hex'') where email_hash is null';
    execute 'alter table public.dr1p_cupones alter column email drop not null';
  end if;
  update public.dr1p_cupones
  set email_hash = encode(digest(lower(codigo), 'sha256'), 'hex')
  where email_hash is null;
end;
$$;
alter table public.dr1p_cupones alter column email_hash set not null;

alter table public.dr1p_cupones add column if not exists expira_en timestamptz;
update public.dr1p_cupones set expira_en = fecha + interval '24 hours' where expira_en is null;
alter table public.dr1p_cupones alter column expira_en set default (now() + interval '24 hours');
alter table public.dr1p_cupones alter column expira_en set not null;
create index if not exists dr1p_cupones_expira_en_idx on public.dr1p_cupones(expira_en);

-- Se conserva solo el hash del email para limitar la ruleta a un giro cada 24 h.
-- También se registran los giros sin premio; el hash se borra al vencer el plazo.
create table if not exists public.dr1p_giros (
  email_hash text primary key check (email_hash ~ '^[a-f0-9]{64}$'),
  segmento smallint not null check (segmento between 0 and 5),
  premio text not null check (premio in ('10OFF', '15OFF', '20OFF', '5000', 'NONE')),
  cupon text,
  fecha timestamptz not null default now(),
  expira_en timestamptz not null default (now() + interval '24 hours')
);
create index if not exists dr1p_giros_expira_en_idx on public.dr1p_giros(expira_en);

create table if not exists public.dr1p_pedidos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  items jsonb not null,
  subtotal integer not null,
  cupon_codigo text,
  descuento integer not null default 0,
  total integer not null,
  fecha timestamptz not null default now()
);

create table if not exists public.dr1p_contactos (
  id bigint generated by default as identity primary key,
  nombre text not null default '',
  email text not null default '',
  telefono text not null default '',
  mensaje text not null default '',
  fecha timestamptz not null default now()
);

alter table public.dr1p_cupones enable row level security;
alter table public.dr1p_giros enable row level security;
alter table public.dr1p_pedidos enable row level security;
alter table public.dr1p_contactos enable row level security;

create or replace function public.issue_dr1p_coupon(p_email_hash text, p_segmento integer, p_cupon text)
returns table(cupon text, premio text, repetido boolean, bloqueado boolean, reintentar_en timestamptz, segmento integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cupon text;
  v_premio text;
  v_segmento integer;
  v_expira timestamptz;
  v_nuevo_premio text;
begin
  if p_email_hash !~ '^[a-f0-9]{64}$' or p_segmento < 0 or p_segmento > 5 then
    raise exception 'invalid_spin_input';
  end if;

  perform pg_advisory_xact_lock(hashtext(p_email_hash));

  select g.cupon, g.premio, g.segmento, g.expira_en
    into v_cupon, v_premio, v_segmento, v_expira
  from public.dr1p_giros g
  where g.email_hash = p_email_hash and g.expira_en > now()
  limit 1;

  if found then
    if v_cupon is not null and exists (
      select 1 from public.dr1p_cupones c
      where c.codigo = v_cupon and c.usado = false and c.expira_en > now()
    ) then
      return query select v_cupon, v_premio, true, false, v_expira, v_segmento;
    else
      return query select null::text, v_premio, false, true, v_expira, v_segmento;
    end if;
    return;
  end if;

  delete from public.dr1p_giros where email_hash = p_email_hash;
  v_nuevo_premio := case p_segmento
    when 0 then '10OFF'
    when 1 then 'NONE'
    when 2 then '15OFF'
    when 3 then 'NONE'
    when 4 then '20OFF'
    else '5000'
  end;

  if v_nuevo_premio = 'NONE' then
    insert into public.dr1p_giros(email_hash, segmento, premio)
    values (p_email_hash, p_segmento, v_nuevo_premio);
    return query select null::text, v_nuevo_premio, false, false, now() + interval '24 hours', p_segmento;
    return;
  end if;

  if p_cupon is null then raise exception 'coupon_code_required'; end if;
  insert into public.dr1p_cupones(codigo, email_hash, premio)
  values (p_cupon, p_email_hash, v_nuevo_premio);
  insert into public.dr1p_giros(email_hash, segmento, premio, cupon)
  values (p_email_hash, p_segmento, v_nuevo_premio, p_cupon);
  return query select p_cupon, v_nuevo_premio, false, false, now() + interval '24 hours', p_segmento;
end;
$$;

create or replace function public.consume_dr1p_coupon(
  p_codigo text,
  p_nombre text,
  p_items jsonb,
  p_subtotal integer,
  p_fecha timestamptz
)
returns table(ok boolean, descuento integer, total integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_premio text;
  v_descuento integer;
  v_total integer;
begin
  update public.dr1p_cupones c
  set usado = true, usado_en = now()
  where c.codigo = p_codigo and c.usado = false and c.expira_en > now()
  returning c.premio into v_premio;

  if not found then
    return query select false, 0, p_subtotal;
    return;
  end if;

  v_descuento := case v_premio
    when '10OFF' then round(p_subtotal * 0.10)::integer
    when '15OFF' then round(p_subtotal * 0.15)::integer
    when '20OFF' then round(p_subtotal * 0.20)::integer
    else least(5000, p_subtotal)
  end;
  v_total := p_subtotal - v_descuento;

  insert into public.dr1p_pedidos(nombre, items, subtotal, cupon_codigo, descuento, total, fecha)
  values (p_nombre, p_items, p_subtotal, p_codigo, v_descuento, v_total, p_fecha);

  return query select true, v_descuento, v_total;
end;
$$;

create or replace function public.cleanup_dr1p_expired_coupons()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.dr1p_cupones where expira_en <= now();
  delete from public.dr1p_giros where expira_en <= now();
end;
$$;

grant all on public.dr1p_cupones, public.dr1p_giros, public.dr1p_pedidos, public.dr1p_contactos to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.issue_dr1p_coupon(text, integer, text) from public, anon, authenticated;
revoke all on function public.consume_dr1p_coupon(text, text, jsonb, integer, timestamptz) from public, anon, authenticated;
revoke all on function public.cleanup_dr1p_expired_coupons() from public, anon, authenticated;
grant execute on function public.issue_dr1p_coupon(text, integer, text) to service_role;
grant execute on function public.consume_dr1p_coupon(text, text, jsonb, integer, timestamptz) to service_role;

-- Limpia cupones y hashes de giro vencidos cada 15 minutos; los usados se conservan solo hasta su expiración.
create extension if not exists pg_cron;
do $$
declare
  v_job_id bigint;
begin
  for v_job_id in select jobid from cron.job where jobname = 'dr1p-clean-expired-coupons' loop
    perform cron.unschedule(v_job_id);
  end loop;
  perform cron.schedule(
    'dr1p-clean-expired-coupons',
    '*/15 * * * *',
    $job$select public.cleanup_dr1p_expired_coupons();$job$
  );
end;
$$;

